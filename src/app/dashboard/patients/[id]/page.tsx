"use client";

import { Suspense, useMemo, useState } from "react";
import Link from "next/link";
import { useParams, useRouter, useSearchParams } from "next/navigation";
import { ArrowLeft, Download, Info, Zap } from "lucide-react";
import { HesitationMap, SegmentChart, ThirdsChart, TrendChart, TrialChart, type TrendPoint } from "@/components/dashboard/charts";
import { SampleBadge } from "@/components/dashboard/sample-badge";
import { ScoreTable, ValidityChips, formatValue } from "@/components/dashboard/score-table";
import { TrailReplay } from "@/components/dashboard/trail-replay";
import { useApi } from "@/components/dashboard/use-api";
import { buttonVariants } from "@/components/ui/button";
import type { PatientDTO, ResultDTO, SessionDTO } from "@/lib/api-types";
import { TASK_LABELS, TASK_TYPES } from "@/lib/events";
import { trailLayout, type TrailCircle } from "@/lib/tasks/protocol";
import { cn } from "@/lib/utils";

export default function PatientPage() {
  return (
    <Suspense fallback={<div className="h-96 animate-pulse rounded-2xl bg-muted/40" />}>
      <PatientView />
    </Suspense>
  );
}

const date = (iso: string) => new Date(iso).toLocaleDateString(undefined, { month: "short", day: "numeric", year: "numeric" });

function PatientView() {
  const { id } = useParams<{ id: string }>();
  const search = useSearchParams();
  const router = useRouter();
  const { data: patient, error, loading } = useApi<PatientDTO>(`/api/patients/${id}`);

  if (loading) return <div className="h-96 animate-pulse rounded-2xl bg-muted/40" />;
  if (error || !patient)
    return (
      <div className="py-16">
        <h1 className="text-2xl font-semibold">Patient not found</h1>
        <Link href="/dashboard" className="mt-3 inline-block text-sm text-primary hover:underline">
          ← All patients
        </Link>
      </div>
    );

  const sessions = patient.sessions;
  const selected = sessions.find((s) => s.id === search.get("session")) ?? [...sessions].reverse().find((s) => s.results.length) ?? sessions.at(-1);
  const select = (sid: string) => router.replace(`/dashboard/patients/${id}?session=${sid}`, { scroll: false });

  return (
    <div className="flex flex-col gap-6">
      <Link href="/dashboard" className="inline-flex w-fit items-center gap-1.5 text-sm text-muted-foreground hover:text-foreground">
        <ArrowLeft className="size-4" /> All patients
      </Link>

      {patient.isSample && (
        <div className="flex items-start gap-3 rounded-2xl bg-status-warn/15 px-5 py-3 text-sm ring-1 ring-status-warn/40">
          <Info className="mt-0.5 size-4 shrink-0" />
          <span>
            <strong>Sample data.</strong> Fictional patient generated by the seed script — not a real child.
          </span>
        </div>
      )}

      <header className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <h1 className="font-mono text-3xl font-semibold tracking-tight">
            {patient.code}
            {patient.isSample && <SampleBadge />}
          </h1>
          <dl className="mt-1 flex flex-wrap gap-x-5 text-sm text-muted-foreground">
            <div>Age {patient.age}</div>
            <div>Grade {patient.grade || "—"}</div>
            <div className="capitalize">{patient.dominantHand}-handed</div>
            <div>{sessions.length} sessions</div>
          </dl>
        </div>
      </header>

      {sessions.length > 0 && <TrendCard sessions={sessions} />}

      <section className="flex flex-col gap-3">
        <h2 className="text-sm font-semibold">Sessions</h2>
        <div className="flex flex-wrap gap-2" role="tablist" aria-label="Sessions">
          {sessions.map((s, i) => (
            <button
              key={s.id}
              role="tab"
              aria-selected={s.id === selected?.id}
              onClick={() => select(s.id)}
              className={cn(
                "rounded-xl border px-3 py-2 text-left text-sm transition-colors",
                s.id === selected?.id ? "border-primary bg-accent/60 ring-1 ring-primary" : "bg-card hover:bg-muted/60",
              )}
            >
              <div className="font-medium">
                #{i + 1} · {date(s.startedAt)}
              </div>
              <div className="flex items-center gap-1 text-xs text-muted-foreground">
                {s.protocol === "quick" && <Zap className="size-3" />}
                {s.protocol} · {s.inputType} · {s.results.length}/{TASK_TYPES.length} tasks
              </div>
            </button>
          ))}
        </div>
      </section>

      {selected && <SessionDetail key={selected.id} session={selected} />}
    </div>
  );
}

function SessionDetail({ session }: { session: SessionDTO }) {
  const byTask = new Map(session.results.map((r) => [r.taskType, r]));
  return (
    <section className="flex flex-col gap-5">
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border bg-card px-5 py-3 text-sm">
        <dl className="flex flex-wrap gap-x-6 gap-y-1">
          <Meta k="Started" v={new Date(session.startedAt).toLocaleString()} />
          <Meta k="Clinician" v={session.clinician.name} />
          <Meta k="Protocol" v={session.protocol} />
          <Meta k="Input" v={session.inputType} />
          <Meta k="Screen" v={`${session.screenWidth}×${session.screenHeight} @${session.deviceInfo.devicePixelRatio ?? "?"}x`} />
        </dl>
        <div className="flex gap-2">
          <a href={`/api/sessions/${session.id}/export?format=csv`} className={buttonVariants({ variant: "outline", size: "sm" })} download>
            <Download /> CSV
          </a>
          <a href={`/api/sessions/${session.id}/export?format=json`} className={buttonVariants({ variant: "outline", size: "sm" })} download>
            <Download /> JSON
          </a>
        </div>
      </div>
      {session.protocol === "quick" && (
        <p className="flex items-center gap-2 rounded-xl bg-secondary px-4 py-2 text-sm text-secondary-foreground">
          <Zap className="size-4" /> Quick demo protocol — shortened tasks; not comparable to standard sessions.
        </p>
      )}
      {TASK_TYPES.map((t) => {
        const r = byTask.get(t);
        return r ? <TaskCard key={t} result={r} sessionId={session.id} /> : <MissingTask key={t} label={TASK_LABELS[t]} />;
      })}
    </section>
  );
}

function Meta({ k, v }: { k: string; v: string }) {
  return (
    <div className="flex gap-1.5">
      <dt className="text-muted-foreground">{k}</dt>
      <dd className="font-medium capitalize">{v}</dd>
    </div>
  );
}

function MissingTask({ label }: { label: string }) {
  return <div className="rounded-2xl border border-dashed px-5 py-4 text-sm text-muted-foreground">{label} — no result for this session.</div>;
}

function TaskCard({ result, sessionId }: { result: ResultDTO; sessionId: string }) {
  const m = result.metrics;
  const circles = useCircles(result);
  return (
    <article className="flex flex-col gap-4 rounded-2xl border bg-card p-5 md:p-6" data-testid={`task-${result.taskType}`}>
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h3 className="text-lg font-semibold">{TASK_LABELS[result.taskType]}</h3>
          <div className="mt-0.5 flex flex-wrap gap-x-3 text-xs text-muted-foreground">
            <span data-testid="metrics-version">metrics v{result.version}</span>
            <span>protocol {m.taskVersion}</span>
            {m.form != null && <span>form {String.fromCharCode(65 + m.form)}</span>}
          </div>
        </div>
        <ValidityChips flags={m.validity} />
      </div>

      <div className="grid gap-5 lg:grid-cols-[minmax(0,0.9fr)_minmax(0,1.1fr)]">
        <ScoreTable result={result} />
        <div className="grid content-start gap-3 sm:grid-cols-2">
          {result.taskType === "trail-making" ? (
            <>
              <SegmentChart segments={m.charts.segments ?? []} part="A" />
              <SegmentChart segments={m.charts.segments ?? []} part="B" />
              {circles.B && <HesitationMap hesitations={m.charts.hesitations ?? []} circles={circles.B} part="B" />}
              <ThirdsChart thirds={m.charts.thirds ?? []} unitLabel="mean segment time" />
            </>
          ) : (
            <>
              <div className="sm:col-span-2">
                <TrialChart trials={m.charts.trials ?? []} title={result.taskType === "spatial-span" ? "Response duration per sequence" : "Response time per trial"} />
              </div>
              {m.charts.thirds?.length ? <ThirdsChart thirds={m.charts.thirds} unitLabel={m.charts.thirds[0].label} /> : null}
            </>
          )}
        </div>
      </div>

      {result.taskType === "trail-making" && (
        <div>
          <h4 className="mb-2 text-sm font-semibold">Path replay · hesitations highlighted</h4>
          <TrailReplay sessionId={sessionId} />
        </div>
      )}
    </article>
  );
}

/** Circle layout for the hesitation map: layouts are deterministic per (part, circle count, form). */
function useCircles(result: ResultDTO): Partial<Record<"A" | "B", TrailCircle[]>> {
  return useMemo(() => {
    if (result.taskType !== "trail-making") return {};
    const segs = result.metrics.charts.segments ?? [];
    const form = result.metrics.form ?? 0;
    const out: Partial<Record<"A" | "B", TrailCircle[]>> = {};
    for (const part of ["A", "B"] as const) {
      const n = segs.filter((x) => x.part === part).length + 1;
      if (n > 1) out[part] = trailLayout(part, n, form);
    }
    return out;
  }, [result]);
}

/* ---------------- Session-over-session ---------------- */

type MetricOption = { id: string; task: (typeof TASK_TYPES)[number]; key: string; label: string; unit: string };

function TrendCard({ sessions }: { sessions: SessionDTO[] }) {
  const options = useMemo(() => {
    const seen = new Map<string, MetricOption>();
    for (const s of sessions)
      for (const r of s.results)
        for (const m of r.metrics.metrics)
          if (m.kind === "score" && !seen.has(`${r.taskType}:${m.key}`))
            seen.set(`${r.taskType}:${m.key}`, { id: `${r.taskType}:${m.key}`, task: r.taskType, key: m.key, label: m.label, unit: m.unit });
    return [...seen.values()];
  }, [sessions]);
  const [metricId, setMetricId] = useState("trail-making:timeB");
  const opt = options.find((o) => o.id === metricId) ?? options[0];
  if (!opt) return null;

  const points: TrendPoint[] = sessions.map((s, i) => {
    const r = s.results.find((x) => x.taskType === opt.task);
    const metric = r?.metrics.metrics.find((x) => x.key === opt.key);
    const n = r?.normComparison[opt.key];
    return { label: `#${i + 1} ${date(s.startedAt)}`, value: metric?.value ?? null, quick: s.protocol === "quick", flagged: n?.status === "compared" && n.flag };
  });
  const versions = [...new Set(sessions.flatMap((s) => s.results.filter((r) => r.taskType === opt.task).map((r) => r.version)))];

  return (
    <section className="rounded-2xl border bg-card p-5">
      <div className="mb-3 flex flex-wrap items-center justify-between gap-3">
        <h2 className="text-sm font-semibold">Session-over-session</h2>
        <select value={opt.id} onChange={(e) => setMetricId(e.target.value)} className="h-9 rounded-lg border bg-background px-2 text-sm" aria-label="Metric to compare">
          {TASK_TYPES.map((t) => (
            <optgroup key={t} label={TASK_LABELS[t]}>
              {options
                .filter((o) => o.task === t)
                .map((o) => (
                  <option key={o.id} value={o.id}>
                    {o.label}
                  </option>
                ))}
            </optgroup>
          ))}
        </select>
      </div>
      <TrendChart data={points} metricLabel={opt.label} unit={opt.unit} />
      <div className="mt-2 flex flex-wrap items-center justify-between gap-2 text-xs text-muted-foreground">
        <span>Hollow point = quick-demo protocol (not comparable) · red outline = norm flag</span>
        <span>
          {points.map((p) => (p.value == null ? "—" : formatValue({ value: p.value, unit: opt.unit as never }))).join(" → ")}
          {versions.length > 1 && <strong className="ml-2 text-status-serious">Mixed metrics versions: {versions.join(", ")}</strong>}
        </span>
      </div>
    </section>
  );
}
